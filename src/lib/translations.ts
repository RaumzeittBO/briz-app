export function t(text: string | undefined | null, lang: Language): string {
    if (!text) return '';
    if (lang === 'es') return text;
    const trimmed = text.trim();
    return translationDict[trimmed] || translationDict[text] || text;
}

/**
 * Helper for dynamic Firestore entities (InventoryItem, ComboProduct, EventItem, CyclingRoute)
 * that may optionally store explicit `nameEn` / `descriptionEn` / `detailsEn` fields.
 */
export function getLocalizedField(
    esValue: string | undefined | null,
    enValue: string | undefined | null,
    lang: Language
): string {
    if (lang === 'en') {
        if (enValue && enValue.trim()) return enValue.trim();
        return t(esValue, 'en');
    }
    return esValue || '';
}
